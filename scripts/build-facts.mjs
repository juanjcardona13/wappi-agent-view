import { readFileSync, writeFileSync } from 'node:fs';

const md = readFileSync(new URL('../docs/ARCHITECTURE-FACTS.md', import.meta.url), 'utf8');
const lines = md.split('\n');

let section = '';
const facts = [];

for (const line of lines) {
  const heading = line.match(/^##\s+(\d+)\.\s+(.*)$/);
  if (heading) {
    section = `${heading[1]}. ${heading[2].trim()}`;
    continue;
  }
  if (!line.startsWith('| F-')) continue;
  const cells = line
    .split('|')
    .slice(1, -1)
    .map((cell) => cell.trim());
  if (cells.length < 3) continue;

  const id = cells[0];
  let text = '';
  let source = '';
  if (cells.length >= 4) {
    text = `${cells[1]} — ${cells[2]}`;
    source = cells[3];
  } else {
    text = cells[1];
    source = cells[2];
  }

  let certainty = 'verificado';
  if (text.includes('[GENERAL]')) certainty = 'general';
  else if (text.includes('[NO VERIFICADO')) certainty = 'no-verificado';

  text = text
    .replaceAll('[GENERAL]', '')
    .replaceAll('[NO VERIFICADO hoy]', 'No verificado hoy:')
    .replaceAll('[NO VERIFICADO]', 'No verificado:')
    .replace(/\s+/g, ' ')
    .trim();

  facts.push({ id, section, text, source, certainty });
}

const unknowns = [];
let inUnknowns = false;
for (const line of lines) {
  if (line.startsWith('## 16.')) {
    inUnknowns = true;
    continue;
  }
  if (inUnknowns && line.startsWith('## ')) break;
  if (!inUnknowns) continue;
  const match = line.match(/^- (U-\d+)\s+(.*)$/);
  if (match) unknowns.push({ id: match[1], text: match[2].trim() });
}

const factSrc = `/* Generated by scripts/build-facts.mjs from docs/ARCHITECTURE-FACTS.md. Do not edit by hand. */
import type { Fact } from './types';

export const facts: Fact[] = ${JSON.stringify(facts, null, 2)};

export const factsById: Record<string, Fact> = Object.fromEntries(
  facts.map((fact) => [fact.id, fact]),
);
`;

const unknownSrc = `/* Generated by scripts/build-facts.mjs from docs/ARCHITECTURE-FACTS.md. Do not edit by hand. */
import type { Unknown } from './types';

export const unknowns: Unknown[] = ${JSON.stringify(unknowns, null, 2)};
`;

writeFileSync(new URL('../src/content/facts.ts', import.meta.url), factSrc);
writeFileSync(new URL('../src/content/unknowns.ts', import.meta.url), unknownSrc);

const ids = facts.map((fact) => fact.id);
const dupes = ids.filter((id, index) => ids.indexOf(id) !== index);
if (dupes.length) {
  console.error('Duplicate fact ids', dupes);
  process.exit(1);
}
console.log(`facts ${facts.length} unknowns ${unknowns.length}`);
